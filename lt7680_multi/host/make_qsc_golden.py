"""Points and their face pixels from qsc.py, for test/test_qsc.cpp.

    python3 host/make_qsc_golden.py > test/qsc_golden.h
"""
import math
import random

import qsc

random.seed(2)
rows = []
for _ in range(2000):
    z = random.uniform(-1, 1)
    a = random.uniform(-math.pi, math.pi)
    lat, lon = math.degrees(math.asin(z)), math.degrees(a)
    f, x, y = qsc.to_face_pixel(lat, lon, 139.767, 480)
    rows.append(f"  {{{lat:.9f}, {lon:.9f}, {f}, {x:.6f}, {y:.6f}}},")
print("// generated by host/make_qsc_golden.py from host/qsc.py (checked against PROJ by host/test_qsc.py)")
print("struct QscGolden { double lat, lon; int face; double x, y; };")
print("static const QscGolden QSC_GOLDEN[] = {")
print("\n".join(rows))
print("};")
