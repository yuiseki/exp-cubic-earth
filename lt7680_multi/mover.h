#pragma once

// #D の架空の飛行機と船。位置は地球の上の単位ベクトル p、進む向きは p に直交する単位ベクトル d で、
// 1 コマごとに大円に沿って speed (ラジアン) 進む。画面には、その点が載る面を映している基板に描く
struct Mover {
  float p[3], d[3];
  float speed;
  int size;  // 印の一辺 (画素)
  bool ship;
  char label[8];  // 印の横に出す名前 (空なら出さない)
  int board;      // 描いている基板 (-1 = どの基板の面にも載っていない)
  int mx, my;     // 描いている印の左上 (パネルの座標)
  int lx, ly;     // 描いているラベルの左上
  int lq;         // ラベルの向き: 文字の下が 0 下、1 右、2 上、3 左 (その場所の南の向き)
  int bx, by, bw, bh;  // 印とラベルを囲む四角
};

// #G (ダブルバッファ版) の 1 機。描く絵 (スプライト) は起動時に表示用メモリへ描いておき、毎コマそこから写す
struct GMover {
  float p[3], d[3];
  float speed;
  int size;
  bool ship;
  char label[8];
  int rx[2], ry[2], rw[2], rh[2], rb[2];  // ページ 0、1 に描いた四角と基板 (rb = -1 なら描いていない)
  int eb, ex, ey, ew, eh;  // このコマで消す四角と基板 (裏のページの記録をコマの最初に写す。描くときに記録を上書きするので)
  bool hidden;  // #t: 今は飛んでいない (前後のキーフレームのどちらかが地上か記録なし)
  int nb, cx, cy, f, fx, fy, q;  // このコマで描く基板 (-1 = 映っていない)、パネルの上の中心、面と画像の座標、ラベルの向き
};

// #G のスプライトの形: 向き q ごとの大きさ、ブロックの中の置き場所、印の左上、ラベルの左上 (スプライトの中の座標)
struct SpriteGeom { int w, h, ox, oy, mx, my, lx, ly; };
